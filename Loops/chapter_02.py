# For loops are used to iterate over a sequence of items. 
# In this example, 
# we will serve chai to customers with token numbers from 1 to 10.
for token in range(1, 11):
    print(f"Serving chai to token #{token}")

# The range() function generates a sequence of numbers. 
# In this case, it generates numbers from 1 to 10 (inclusive). T
# he for loop iterates over each number in the sequence, and the print statement serves chai to each token number.
for token in range(11):
    print(f"Serving chai to token #{token}")